      '  "category": "General",\n'
      '  "time": "05:00 PM"\n'
      '}\n'
      '```';

  /// Offline fallback message shown when AI is unavailable.
  static String offlineFallback(String summaryLine) =>
      '📴 AI responses require an internet connection.\n\n'
      'Here\'s your current progress from local data:\n'
      '$summaryLine\n\n'
      'All your habits, tasks, journal, and timetable features '
      'continue to work fully offline.';

  /// Short message shown when API key is not configured.
  static const String apiKeyMissingMessage =
      '⚙️ Grow AI is not yet configured.\n\n'
      'To enable AI chat, run the app with:\n'
      '`flutter run --dart-define=GEMINI_API_KEY=YOUR_KEY`\n\n'
      'You can get a free API key at aistudio.google.com\n\n'
      'All other Grow features work normally without the AI.';
}
