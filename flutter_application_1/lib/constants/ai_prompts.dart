      'When the user explicitly asks you to generate, create, or schedule '
      'in-app routines, tasks, habits, or reminders, include an action JSON '
      'block at the very end of your response.\n\n'
      'A. Timetable/Schedule:\n'
      '```json\n'
      '{\n'
      '  "action": "timetable",\n'
      '  "slots": [\n'
      '    {"title": "Deep Work", "startTime": "09:00 AM", '
